/*
 * The Related posts list under a post, with its "Titles are generated by AI from Meta" line (#231).
 * Read from 584, 2026-10-24; the obfuscated names are for reviewers, the code never writes one down.
 *
 * It's a plugin of the socket under a post's buttons ([POST_SOCKET]), the one Meta AI's inline
 * comment summary goes through: the socket's name table (584 LX/228;->A0k) names it with the
 * summary, and the socket asks the same per-plugin check whether it applies. The hook goes first in
 * that check, like the summary's, and while the switch is on the Related posts plugin gets a no, so
 * the socket goes on to the next plugin. Both hooks can sit in the check, each asking only about its
 * own plugin.
 *
 * A post opened on its own gets the list a second way (#231 again, read from 585, 2026-11-01). The
 * comment screen's bottom socket ([COMMENT_BOTTOM_SOCKET], 585 LX/09t0;->A0o) draws it after the
 * comments as a full list of posts, through its own name table (LX/01xX;->A0u, the list's plugin at
 * 9 of 0 to 9) and its own per-plugin check (LX/01xX;->A2A), so the same hook goes first in that
 * check. The list is asked for with the post's comments: [RELATED_REQUEST], a kept class, answers
 * whether the request (585 LX/09i5;->A00 for comments, LX/0ANo;->A03 for a single post) adds
 * is_seo_landing and show_related_content_in_permalink. Answering no there sends the request as it
 * goes for an account Facebook never shows the list to.
 */

private const val PATCH = "Hide suggested and promoted posts"

/** The Related posts plugin under a post's buttons, a kept class name the socket's name table loads. */
internal const val RELATED_POSTS =
    "com.facebook.feed.plugins.belowufifooter.impl.inlinerelatedposts.InlineRelatedPostsPlugin"

/** The Related posts list after a post's comments, a kept class name the bottom socket's table loads. */
internal const val RELATED_AFTER_COMMENTS =
    "com.facebook.feedback.comments.plugins.bottomcontent.impl.relatedcontent.RelatedContentPlugin"

/** The comment screen's socket under the comments, by the name its method logs. */
internal const val COMMENT_BOTTOM_SOCKET = "FeedbackSurfaceBottomContentSocket"

/** The plugin that decides whether a post's request asks for the Related posts list, a kept class. */
internal const val RELATED_REQUEST =
    "Lcom/facebook/feedback/comments/plugins/commentqueryparams/relatedcontent/RelatedContentQueryPlugin;"

internal const val HOLDS_RELATED_POSTS = "$EXTENSION_PACKAGE/feed/RelatedPosts;->holds(Ljava/lang/String;)Z"

internal const val KEEPS_OUT_OF_REQUEST = "$EXTENSION_PACKAGE/feed/RelatedPosts;->keepsOutOfRequest()Z"

/** Hooks the check of the socket under a post's buttons, so the Related posts plugin can be left out. */
internal fun BytecodePatchContext.hookRelatedPosts() {
    hookSocket(POST_SOCKET, RELATED_POSTS)
}

/** Hooks the check of the comment screen's bottom socket, so its Related posts plugin can be left out. */
internal fun BytecodePatchContext.hookRelatedPostsAfterComments() {
    hookSocket(COMMENT_BOTTOM_SOCKET, RELATED_AFTER_COMMENTS)
}

private fun BytecodePatchContext.hookSocket(name: String, plugin: String) {
    val socket = pluginSocket(name, plugin, patch = PATCH)
    mutableClassDefBy(socket.check.definingClass).methods.single { it.descriptor() == socket.check.descriptor() }
        .holdSummaries(socket.table, HOLDS_RELATED_POSTS, PATCH)
}

/** Has the request's plugin answer no while the switch is on, so the list isn't asked for. */
internal fun BytecodePatchContext.hookRelatedPostsRequest() {
    val plugin = classDefByOrNull(RELATED_REQUEST) ?: throw PatchException("$PATCH: $RELATED_REQUEST isn't in this APK")
    val decider = requestDecider(plugin)
    mutableClassDefBy(plugin.type).methods.single { it.descriptor() == decider.descriptor() }.answerNoWhenKept()
}

/** The plugin's one static (Z)Z method, its answer to whether the request asks for the list. */
internal fun requestDecider(plugin: ClassDef): Method {
    val deciders = plugin.methods.filter { method ->
        AccessFlags.STATIC.isSet(method.accessFlags) && method.returnType == "Z" &&
            method.parameterTypes.map(CharSequence::toString) == listOf("Z") && method.implementation != null
    }
    return deciders.singleOrNull()
        ?: throw PatchException("$PATCH: expected one static (Z)Z in ${plugin.type}, found ${deciders.size}")
}

/** First thing in the decider: a yes from [KEEPS_OUT_OF_REQUEST] answers no, otherwise it runs as written. */
internal fun MutableMethod.answerNoWhenKept() {
    requireLocals(PATCH, 1)
    addInstructionsWithLabels(
        0,
        """
            invoke-static { }, $KEEPS_OUT_OF_REQUEST
            move-result v0
            if-eqz v0, :ask
            const/4 v0, 0x0
            return v0
        """,
        ExternalLabel("ask", getInstruction(0)),
    )
}
